
import React, { useState, useMemo, useEffect } from 'react';
import type { Личность, Контакт, Чат, Сообщение, Группа, Магазин, ДоскаОбъявлений } from './types';
import { useLocalStorage } from './hooks/useLocalStorage';
import CreateIdentity from './components/CreateIdentity';
import ContactList from './components/ContactList';
import ChatWindow from './components/ChatWindow';
import { сгенерироватьЛичность, зашифровать } from './services/cryptoService';
import { WelcomePlaceholder } from './components/WelcomePlaceholder';
import { сервисАПИ } from './services/apiService';
import ProfileDrawer from './components/ProfileDrawer';
import StoreManagementModal from './components/StoreManagementModal';
import BoardManagementModal from './components/BoardManagementModal';
import CreateBoardModal from './components/CreateBoardModal';
import VerificationModal from './components/VerificationModal';
import QRScanningModal from './components/QRScanningModal';

const App: React.FC = () => {
  const [личность, установитьЛичность] = useLocalStorage<Личность | null>('cipherlink-identity', null);
  const [контакты, установитьКонтакты] = useLocalStorage<Контакт[]>('cipherlink-contacts', []);
  const [группы, установитьГруппы] = useLocalStorage<Группа[]>('cipherlink-groups', []);
  const [чаты, установитьЧаты] = useLocalStorage<Record<string, Чат>>('cipherlink-chats', {});
  const [выбранныйЧатId, установитьВыбранныйЧатId] = useState<string | null>(null);
  const [профильОткрыт, установитьПрофильОткрыт] = useState(false);
  const [глобальноеБезмолвиеДо, установитьГлобальноеБезмолвиеДо] = useLocalStorage<number | 'навсегда' | null>('cipherlink-global-mute', null);
  const [тема, установитьТему] = useLocalStorage<'dark' | 'light'>('cipherlink-theme', 'dark');

  // Новые состояния для управления досками и магазинами
  const [модалМагазинаОткрыт, установитьМодалМагазинаОткрыт] = useState(false);
  const [модалДосокОткрыт, установитьМодалДосокОткрыт] = useState(false);
  const [модалСозданияДоскиОткрыт, установитьМодалСозданияДоскиОткрыт] = useState(false);
  const [активнаяДоскаДляУправления, установитьАктивнаяДоскаДляУправления] = useState<ДоскаОбъявлений|null>(null);
  const [заказыМагазина, установитьЗаказыМагазина] = useState<any[]>([]);

  // Верификация
  const [модалВерификацииОткрыт, установитьМодалВерификацииОткрыт] = useState(false);
  const [модалСканированияОткрыт, установитьМодалСканированияОткрыт] = useState(false);

  // Применение темы
  useEffect(() => {
    document.documentElement.className = тема;
  }, [тема]);

  // Инициализация системного чата
  useEffect(() => {
    if (!контакты.find(c => c.uid === 'system')) {
        const системныйКонтакт: Контакт = { id: 'system_chat', uid: 'system', имя: 'Системные Уведомления', проверен: true };
        установитьКонтакты(prev => [системныйКонтакт, ...prev]);
        установитьЧаты(prev => ({ ...prev, 'system_chat': { idКонтакта: 'system_chat', сообщения: [] } }));
    }
  }, []);

  useEffect(() => {
    if (личность) {
      сервисАПИ.подключиться(личность.uid);

      const обработатьСообщение = (сообщение: Сообщение) => {
        let чатId = '';
        
        if (сообщение.idГруппы) {
            const группа = группы.find(g => g.id === сообщение.idГруппы);
            if (!группа) return;
            чатId = группа.id;
        } else if (сообщение.idОтправителя === 'system' || сообщение.тип === 'системное') {
            чатId = 'system_chat';
        } else {
            // Если это заказ
            if (сообщение.payload && сообщение.payload.тип === 'заказ') {
                установитьЗаказыМагазина(prev => [...prev, { ...сообщение.payload, id: сообщение.payload.заказId, покупательUid: сообщение.idОтправителя }]);
            }
            // Обработка статусов "прочитано"
            if (сообщение.тип === 'прочитано') {
                 // Здесь можно найти чат и обновить статусы исходящих сообщений
                 return; 
            }
            
            const контакт = контакты.find(c => c.uid === сообщение.idОтправителя);
            if (!контакт) {
                return; 
            }
            чатId = контакт.id;
        }

        установитьЧаты(предыдущиеЧаты => {
            const текущийЧат = предыдущиеЧаты[чатId] || { idКонтакта: чатId, сообщения: [] };
            if (текущийЧат.сообщения.some(m => m.id === сообщение.id)) return предыдущиеЧаты;
            const обновленныйЧат = { ...текущийЧат, сообщения: [...текущийЧат.сообщения, сообщение] };
            return { ...предыдущиеЧаты, [чатId]: обновленныйЧат };
        });
      };

      сервисАПИ.приСообщении(обработатьСообщение);
      return () => {
        сервисАПИ.отключиться();
        сервисАПИ.отписатьсяОтСообщений(обработатьСообщение);
      };
    }
  }, [личность, контакты, группы]);


  const обработатьСозданиеЛичности = async () => {
    const новаяЛичность = сгенерироватьЛичность();
    try {
      await сервисАПИ.зарегистрировать(новаяЛичность.uid, новаяЛичность.публичныйКлюч);
      установитьЛичность(новаяЛичность);
    } catch (error) {
      console.error("Ошибка регистрации:", error);
    }
  };
  
  const обработатьДобавлениеКонтакта = (имя: string, uid: string) => {
    if (uid.startsWith('http')) {
        const токен = uid.split('/').pop();
        if (токен) {
            сервисАПИ.присоединитьсяКГруппе(личность!.uid, токен).then(группа => {
                установитьГруппы(prev => [...prev, группа]);
                установитьЧаты(prev => ({ ...prev, [группа.id]: { idКонтакта: группа.id, сообщения: [] } }));
            }).catch(e => alert(e.message));
        }
        return;
    }

    if (!контакты.some(c => c.uid === uid)) {
      const новыйКонтакт: Контакт = { id: crypto.randomUUID(), имя, uid, проверен: false };
      установитьКонтакты([...контакты, новыйКонтакт]);
      установитьЧаты(предыдущиеЧаты => ({ ...предыдущиеЧаты, [новыйКонтакт.id]: { idКонтакта: новыйКонтакт.id, сообщения: [] } }));
    }
  };

  const обработатьСозданиеГруппы = async (название: string, тип: 'публичная' | 'приватная') => {
      if (!личность) return;
      try {
          const группа = await сервисАПИ.создатьГруппу({ название, idВладельца: личность.uid, тип });
          установитьГруппы([...группы, группа]);
          установитьЧаты(prev => ({ ...prev, [группа.id]: { idКонтакта: группа.id, сообщения: [] } }));
      } catch (e) {
          console.error(e);
      }
  };

  const обработатьОтправкуСообщения = (текст: string, медиа?: string, типМедиа?: 'image' | 'video', допДанные?: any) => {
    if (!выбранныйЧатId || !личность) return;
    const контакт = контакты.find(c => c.id === выбранныйЧатId);
    const группа = группы.find(g => g.id === выбранныйЧатId);
    
    let uidПолучателя = '';
    let idГруппы: string | undefined = undefined;

    if (группа) {
        idГруппы = группа.id;
        uidПолучателя = 'server'; 
    } else if (контакт) {
        uidПолучателя = контакт.uid;
    } else return;

    const чат = чаты[выбранныйЧатId];
    const времяИсчезновения = чат?.таймерИсчезновения;
    const таймерУстановленВ = времяИсчезновения ? Date.now() : undefined;

    const сообщение: Сообщение = {
      id: crypto.randomUUID(),
      idОтправителя: личность.uid,
      текст: зашифровать(текст, личность.приватныйКлюч),
      временнаяМетка: new Date().toISOString(),
      статус: 'отправлено',
      idГруппы,
      времяИсчезновения,
      таймерУстановленВ,
      media: медиа,
      mediaType: типМедиа,
      payload: допДанные
    };
    
    сервисАПИ.отправитьСообщение(uidПолучателя, сообщение.текст, { 
      idГруппы, 
      времяИсчезновения, 
      таймерУстановленВ,
      media: медиа,
      mediaType: типМедиа,
      payload: допДанные
    });

    установитьЧаты(предыдущиеЧаты => {
      const обновленныйЧат = { ...предыдущиеЧаты[выбранныйЧатId] };
      обновленныйЧат.сообщения = [...обновленныйЧат.сообщения, сообщение];
      return { ...предыдущиеЧаты, [выбранныйЧатId]: обновленныйЧат };
    });
  };

  const обработатьАрхивациюЧата = (контактId: string, архивировать: boolean) => {
      установитьКонтакты(prev => prev.map(c => c.id === контактId ? { ...c, архивирован: архивировать } : c));
  };

  const обработатьУстановкуТаймера = (секунды: number | undefined) => {
    if (выбранныйЧатId) {
        установитьЧаты(prev => ({
            ...prev,
            [выбранныйЧатId]: { ...prev[выбранныйЧатId], таймерИсчезновения: секунды }
        }));
    }
  };

  const обработатьУдалениеСообщения = (id: string) => {
    if (выбранныйЧатId) {
        установитьЧаты(prev => ({
            ...prev,
            [выбранныйЧатId]: {
                ...prev[выбранныйЧатId],
                сообщения: prev[выбранныйЧатId].сообщения.filter(m => m.id !== id)
            }
        }));
    }
  };

  const обработатьВерификацию = () => {
      установитьМодалСканированияОткрыт(true);
  };
  
  const приУспешномСканировании = (сканированныйUid: string) => {
      if (!выбранныйЧатId) return;
      const контакт = контакты.find(c => c.id === выбранныйЧатId);
      if (контакт && контакт.uid === сканированныйUid) {
          установитьКонтакты(prev => prev.map(c => 
            c.id === выбранныйЧатId ? { ...c, проверен: true } : c
          ));
          alert('Контакт успешно верифицирован!');
      } else {
          alert('Ошибка: UID не совпадает.');
      }
      установитьМодалСканированияОткрыт(false);
  }

  // Магазины и доски
  const сохранитьМагазин = (м: Магазин) => {
      if(личность) установитьЛичность({...личность, магазин: м});
  }
  
  const обновитьСтатусЗаказа = (id: string, новыйСтатус: any) => {
      const заказ = заказыМагазина.find(з => з.id === id);
      if (заказ) {
          установитьЗаказыМагазина(prev => prev.map(з => з.id === id ? {...з, статус: новыйСтатус} : з));
          
          // Отправка уведомления покупателю
          сервисАПИ.отправитьСообщение(заказ.покупательUid, `Статус вашего заказа "${заказ.товар.название}" изменен на: ${новыйСтатус}`, {
              тип: 'системное'
          });
      }
  }

  const создатьДоску = async (данные: any) => {
      if(!личность) return;
      try {
        const {доска} = await сервисАПИ.создатьДоску({...данные, uid: личность.uid});
        const новыеДоски = [...(личность.доски || []), доска];
        установитьЛичность({...личность, доски: новыеДоски});
      } catch(e: any) { alert(e.message); }
  }
  
  const обработатьСбросПриложения = () => {
    if (confirm('Вы уверены? Это удалит вашу личность, все контакты и переписки. Это действие необратимо.')) {
        localStorage.clear();
        window.location.reload();
    }
  };
  
  const обработатьОбновлениеПрофиля = (имя: string, аватар: string) => {
      if(личность) установитьЛичность({...личность, имяПользователя: имя, аватар});
  }

  const выбранныйЧат = useMemo(() => {
    if (!выбранныйЧатId) return null;
    return чаты[выбранныйЧатId] || { idКонтакта: выбранныйЧатId, сообщения: [] };
  }, [выбранныйЧатId, чаты]);

  const выбранныйОбъект = useMemo(() => {
      return контакты.find(c => c.id === выбранныйЧатId) || группы.find(g => g.id === выбранныйЧатId) || null;
  }, [выбранныйЧатId, контакты, группы]);

  if (!личность) {
    return <CreateIdentity приСозданииЛичности={обработатьСозданиеЛичности} />;
  }

  return (
    <div className="flex h-screen w-screen bg-slate-900 font-sans overflow-hidden dark:bg-slate-900 dark:text-slate-200">
      {профильОткрыт && (
        <ProfileDrawer
          личность={личность}
          приЗакрытии={() => установитьПрофильОткрыт(false)}
          глобальноеБезмолвиеДо={глобальноеБезмолвиеДо}
          установитьГлобальноеБезмолвиеДо={установитьГлобальноеБезмолвиеДо}
          приСбросе={обработатьСбросПриложения}
          приОбновленииПрофиля={обработатьОбновлениеПрофиля}
          тема={тема}
          установитьТему={установитьТему}
        />
      )}
      
      <div className={`${выбранныйЧатId ? 'hidden md:flex' : 'flex'} w-full md:w-auto h-full`}>
        <ContactList
            личность={личность}
            контакты={контакты}
            группы={группы}
            приДобавленииКонтакта={обработатьДобавлениеКонтакта}
            выбранныйЧатId={выбранныйЧатId}
            приВыбореЧата={установитьВыбранныйЧатId}
            чаты={чаты}
            приОткрытииПрофиля={() => установитьПрофильОткрыт(true)}
            приБезмолвииЧата={(id, срок) => { /* Логика заглушена */ }}
            приАрхивацииЧата={обработатьАрхивациюЧата}
            приСозданииГруппы={обработатьСозданиеГруппы}
            приОткрытииМагазина={() => установитьМодалМагазинаОткрыт(true)}
            приОткрытииДосок={() => установитьМодалДосокОткрыт(true)}
        />
      </div>

      <main className={`flex-1 flex flex-col bg-slate-800 ${!выбранныйЧатId ? 'hidden md:flex' : 'flex'}`}>
        {выбранныйОбъект && выбранныйЧат ? (
            <ChatWindow
                key={выбранныйОбъект.id}
                собеседник={выбранныйОбъект}
                чат={выбранныйЧат}
                приОтправкеСообщения={обработатьОтправкуСообщения}
                текущаяЛичностьПользователя={личность}
                приВозврате={() => установитьВыбранныйЧатId(null)}
                приУстановкеТаймера={обработатьУстановкуТаймера}
                приУдаленииСообщения={обработатьУдалениеСообщения}
                приВерификации={обработатьВерификацию}
            />
        ) : (
            <WelcomePlaceholder />
        )}
      </main>

      {/* Модальные окна бизнеса */}
      {модалМагазинаОткрыт && (
          <StoreManagementModal 
             личность={личность}
             приЗакрытии={() => установитьМодалМагазинаОткрыт(false)}
             приСохранении={сохранитьМагазин}
             заказы={заказыМагазина}
             обновитьСтатусЗаказа={обновитьСтатусЗаказа}
          />
      )}
      
      {модалДосокОткрыт && (
          <div className="fixed inset-0 bg-black/80 flex items-center justify-center z-50">
              <div className="bg-slate-800 p-6 rounded-lg w-full max-w-md">
                  <h2 className="text-xl font-bold text-white mb-4">Мои доски</h2>
                  <div className="space-y-2 mb-4">
                      {личность.доски?.map(д => (
                          <div key={д.id} className="bg-slate-700 p-3 rounded flex justify-between items-center">
                              <span className="text-white">{д.название}</span>
                              <button onClick={() => установитьАктивнаяДоскаДляУправления(д)} className="bg-cyan-600 px-2 py-1 rounded text-xs text-white">Управлять</button>
                          </div>
                      ))}
                      {(!личность.доски || личность.доски.length === 0) && <p className="text-slate-500">Нет досок</p>}
                  </div>
                  <div className="flex justify-between">
                       <button onClick={() => установитьМодалСозданияДоскиОткрыт(true)} className="bg-green-600 px-4 py-2 rounded text-white">Создать новую</button>
                       <button onClick={() => установитьМодалДосокОткрыт(false)} className="bg-slate-600 px-4 py-2 rounded text-white">Закрыть</button>
                  </div>
              </div>
          </div>
      )}

      {модалСозданияДоскиОткрыт && (
          <CreateBoardModal 
             приЗакрытии={() => установитьМодалСозданияДоскиОткрыт(false)}
             приСоздании={создатьДоску}
          />
      )}

      {активнаяДоскаДляУправления && (
          <BoardManagementModal
             доска={активнаяДоскаДляУправления}
             приЗакрытии={() => установитьАктивнаяДоскаДляУправления(null)}
             приОбновлении={() => {
                 alert('Обновлено');
                 установитьАктивнаяДоскаДляУправления(null);
             }}
          />
      )}

      {/* Модальные окна верификации */}
      {модалВерификацииОткрыт && (
          <VerificationModal 
            uid={личность.uid} 
            отпечаток={личность.отпечатокКлюча || 'UNKNOWN'} 
            приЗакрытии={() => установитьМодалВерификацииОткрыт(false)} 
          />
      )}
      {модалСканированияОткрыт && (
          <QRScanningModal приЗакрытии={() => установитьМодалСканированияОткрыт(false)} приУспехе={приУспешномСканировании} />
      )}

    </div>
  );
};

export default App;
